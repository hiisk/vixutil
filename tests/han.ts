const SIMPLIFIED_ONLY = new Set(PAIRS.map(p => p[0]));
const TRADITIONAL_ONLY = new Set(PAIRS.map(p => p[1]));

/** 반대쪽 글자가 섞였으면 그 글자들을, 없으면 빈 배열을 준다 */
export function strayHan(lang: string, text: string): string[] {
  const wrong = lang === 'zh' ? TRADITIONAL_ONLY : lang === 'tw' ? SIMPLIFIED_ONLY : null;
  if (!wrong) return [];
  const found = new Set<string>();
  for (const ch of text) if (wrong.has(ch)) found.add(ch);
  return [...found];
}

/**
 * 섹션 검사에서 부르는 자리 — 문장 하나를 보고 섞였으면 사람이 읽을 말로 돌려준다.
 * 안 섞였으면 빈 문자열이라, assert.equal(hanProblem(...), '')로 쓴다.
 */
export function hanProblem(lang: string, text: string): string {
  const stray = strayHan(lang, text);
  if (!stray.length) return '';
  const side = lang === 'zh' ? '번체' : '간체';
  return `${lang}: ${side} 글자 ${stray.join('·')}가 섞였다 — ${text}`;
}

