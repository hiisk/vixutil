/**
 * 빌드 때 미리 만들 낱장 수를 정한다.
 *
 * ── 왜 있는가 ────────────────────────────────────────────────────
 * 이 사이트는 낱장이 99,177개다(한 언어당 약 9,800 × 열 언어). 전에는
 * `output: "export"`로 그 전부를 빌드마다 새로 구웠는데, Vercel 무료 티어
 * (2코어 8GB · 45분)에서 감당이 안 됐다 — 컴파일에서 exit 137로 죽거나,
 * 넘겨도 생성만 38분이 걸려 제한에 닿는다.
 *
 * 그래서 만드는 **시점**을 옮겼다. 빌드에서는 정해진 수만큼만 만들고, 나머지는
 * 처음 열릴 때 만들어 CDN에 캐시한다. 두 번째 방문부터는 지금과 똑같다.
 * 페이지는 한 장도 없어지지 않는다 — `dynamicParams`가 기본으로 켜져 있어
 * 목록에 없는 낱장도 그대로 열린다.
 *
 * ── 값을 어떻게 잡는가 ───────────────────────────────────────────
 * 0이면 빌드에서 낱장을 한 장도 안 만든다(허브는 정적 라우트라 그대로 만들어진다).
 * 숫자를 주면 라우트마다 앞에서 그만큼 만든다. 목록의 앞쪽이 대개 대표 항목이라
 * (원소는 수소, 색은 빨강) 크롤러와 사람이 먼저 닿는 것들이 미리 구워진다.
 *
 * 환경변수로 조절한다 — 빌드 시간과 미리 굽는 양의 맞바꿈이라, 나중에 빌드
 * 머신이 커지면 코드를 안 고치고 숫자만 올리면 된다.
 *
 * ── 왜 0이 아니라 100인가 (2026-08-06) ──────────────────────────
 * 0으로 두었더니 **ISR 쓰기 한도**에 걸렸다. 무료 티어가 한 달 20만 번인데
 * 300%를 썼다는 연락이 왔다. 산수는 단순하다.
 *
 *   쓰기 = 크롤러가 훑은 낱장 수 × 배포 횟수
 *
 * 사이트맵이 115,157개를 내걸고 있고 배포하면 ISR 캐시가 차가워지므로,
 * 크롤러가 다시 훑는 만큼 다시 쓴다. 세 번 배포하니 그대로 34만이다.
 *
 * **빌드에서 구운 페이지는 정적이라 ISR 쓰기가 0이다.** 그래서 미리 굽는 만큼
 * 쓰기가 줄어든다. 100이면 61,694장(전체의 54%)이 정적이 되어 훑을 때마다
 * 드는 쓰기가 115,157에서 53,000쯤으로 준다.
 *
 * ── 100으로 올렸다가 되돌린 이유: 디스크 (2026-08-06) ────────────
 * 100으로 배포했더니 Vercel이 48,769/61,694장에서 **ENOSPC(디스크 없음)**로
 * 죽었다. 시간이 아니라 공간이 벽이었다.
 *
 * 페이지 한 장이 디스크에 남기는 것은 셋이다(로컬 실측, 61,694장 기준):
 *   .html      191KB   11.2GB
 *   .rsc       100KB    5.9GB   (HTML 안에 인라인된 것과 별개로 또 쓴다)
 *   .segments  210KB   12.9GB   (세그먼트별 프리페치, 한 장에 파일 열 개)
 *   합계       501KB   30.0GB
 *
 * 그 뒤 되풀이되는 Tailwind 클래스 묶음을 CSS 클래스로 빼서 한 장이
 * 501KB → 441KB가 됐다(HTML 191KB → 149KB). 그만큼 더 구울 수 있다.
 *
 * 48,769장에서 죽었으니 빌드 컨테이너의 여유는 24GB쯤이다.
 * `cacheComponents: false`로 .segments를 끄려 해 봤지만 그대로 나온다 —
 * Next 16이 늘 만든다.
 *
 * 그래서 24로 잡는다. 19,962장 × 441KB = 8.4GB로, 죽은 자리의 35%다.
 * 빌드가 끝나면 Vercel이 산출물을 한 벌 더 복사하므로 절반 아래로 둔다.
 * 시간은 로컬 9분 · Vercel 18분쯤이라 45분 한도에도 여유가 크다.
 *
 * **이것만으로는 ISR 쓰기 한도 안에 못 들어간다.** 미리 굽는 것이 12.7%뿐이라
 * 한 번 훑을 때 여전히 10만 번을 쓴다. 배포를 모아서 하는 것이 같이 가야 하고,
 * 더 올리려면 먼저 **페이지 한 장의 크기**를 줄여야 한다 — 191KB 중 42%가
 * Tailwind 클래스 문자열이고 그것이 .rsc·.segments에도 그대로 실린다.
 */
const LIMIT = Number(process.env.PRERENDER_PER_ROUTE ?? '24');

/**
 * 검사에서는 자르지 않는다.
 *
 * "목록의 모든 항목이 페이지로 나가는가"를 보는 검사가 여럿이다. 그 검사들은
 * 이 함수를 거쳐 목록을 받는데, 여기서 잘라 버리면 전부 0을 보고 "페이지가
 * 없다"고 말한다 — 실제로는 요청 때 만들어지는데도 그렇다.
 *
 * node --test가 켜 주는 환경변수로 가른다. 빌드에는 없는 값이라 실제 빌드가
 * 잘리는 일은 없다.
 */
const IN_TEST = Boolean(process.env.NODE_TEST_CONTEXT);

/** 미리 만들 것만 남긴다. 빈 배열이어도 그 라우트는 정상으로 동작한다. */
export function prerender<T>(all: T[]): T[] {
  if (IN_TEST) return all;
  return LIMIT > 0 ? all.slice(0, LIMIT) : [];
}

/** 지금 몇 장씩 굽고 있는지 — 검사와 로그에서 쓴다 */
export const prerenderLimit = (): number => LIMIT;
