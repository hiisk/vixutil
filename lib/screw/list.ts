export interface Screw {
  /** 수나사 바깥지름(mm) */
  d: number;
  /** 피치 — 나사산 하나에서 다음 산까지(mm) */
  p: number;
  /** 보통 나사인가 — 각 지름에서 가장 굵은 피치 하나 */
  coarse: boolean;
}

export const SCREWS: Screw[] = Object.entries(BY_DIAMETER).flatMap(([d, pitches]) =>
  pitches.map((p, i) => ({ d: Number(d), p, coarse: i === 0 })),
);

/** M8×1.25 → m8x1-25 (소수점은 하이픈으로 — 주소에 점을 두지 않는다) */
export const slugOf = (s: Screw): string =>
  `m${String(s.d).replace('.', '-')}x${String(s.p).replace('.', '-')}`;

/** 사람이 적는 꼴 */
export const labelOf = (s: Screw): string => `M${s.d}×${s.p}`;

export const SCREW_SLUGS = SCREWS.map(slugOf);

export const screwOf = (slug: string): Screw | undefined => SCREWS.find(s => slugOf(s) === slug);

/** 목록과 공유 카드가 같은 그림을 쓴다 */
export const SCREW_ICON = '🔩';

/** 외경만 모은 것 — 목록의 첫 갈래다 */
export const DIAMETERS = [...new Set(SCREWS.map(s => s.d))].sort((a, b) => a - b);
