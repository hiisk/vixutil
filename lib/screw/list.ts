/**
 * 미터 나사 규격 114가지 — 외경과 피치만 적는다.
 *
 * 골지름, 유효지름, 탭 드릴 지름, 응력단면적은 전부 이 둘에서 나온다(facts.ts).
 * ISO 68-1이 나사산을 60도 삼각형으로 정해 두었기 때문에, 외경과 피치가 정해지면
 * 나머지 치수는 계산으로 따라온다.
 *
 * 조합을 계산으로 만들지 않는 이유는 타이어와 같다. M8에 피치 3mm를 물릴 수는
 * 있지만 그런 나사는 팔지 않는다. 그래서 실제로 쓰이는 짝만 적는다.
 *
 * 각 줄의 첫 피치가 보통 나사(coarse)이고 나머지는 가는 나사(fine)다. 이 순서
 * 하나로 "보통이냐 가는이냐"가 정해지므로 따로 표시하지 않는다.
 */

/** 외경(mm): 피치 목록 — 첫 번째가 보통 나사다 */
