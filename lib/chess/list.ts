/**
 * 체스 오프닝 목록 — 적는 것은 수순뿐이다.
 *
 * 자리(FEN)도, 판 그림도, 몇 수째인지도, 어느 갈래에 드는지도 적지 않는다.
 * engine.ts가 수를 실제로 두어 보고 나머지를 만든다. 그래서 수순이 규칙에
 * 어긋나거나 표기가 모호하면 검사에서 예외가 난다 — 표를 옮겨 적는 방식은
 * 한 칸이 틀려도 아무도 못 잡지만, 이쪽은 잡힌다.
 *
 * 장군 표시(+, #)는 적지 않는다. 어느 수가 장군인지는 판이 알고 있다.
 */

export interface Opening {
  slug: string;
  /** names.ts의 계열 열쇠 */
  family: string;
  /** names.ts의 갈래 열쇠 — 없으면 계열 이름만 쓴다 */
  line?: string;
  /** 첫 수부터의 표기 */
  moves: string[];
}

const o = (slug: string, family: string, line: string | null, moves: string): Opening => ({
  slug,
  family,
  ...(line ? { line } : {}),
  moves: moves.split(' '),
});

