import type { MbtiType } from '../mbti-match.ts';

/**
 * 유형마다 손으로 적는 것.
 *
 * ── 무엇을 여기 적고 무엇을 안 적나 ────────────────────────
 * 계산으로 나오는 것은 안 적는다 — 인지기능 순서(functions.ts), 궁합
 * 열여섯(mbti-match.ts), 글자별 뜻, 같은 기질군. 그것들을 여기 또 적으면
 * 두 곳이 갈리고 한쪽만 고쳐진 채 남는다.
 *
 * 여기 적는 것은 계산으로 안 나오는 것뿐이다 — 그 유형을 겪어 본 사람이
 * 알아볼 만한 구체적인 장면.
 *
 * ── 어떻게 적나 ────────────────────────────────────────────
 * 형용사를 늘어놓지 않는다. 「창의적이고 이상적입니다」는 열여섯 중 열에
 * 붙일 수 있어 아무것도 안 말한 것과 같다. 그 유형에서만 나오는 «행동»을
 * 적는다 — 언제 그러는지, 그때 무엇을 하는지.
 */
export interface MbtiProfile {
  /** 한 줄 — 목록과 공유 카드에 쓴다. 스무 자 안쪽 */
  line: string;
  /** 어떤 사람인가 — 세 문장쯤 */
  summary: string;
  /** 잘하는 것 셋 — 각 한 문장 */
  strengths: string[];
  /** 걸리는 것 셋 — 각 한 문장 */
  pitfalls: string[];
  /** 지칠 때 어떻게 되는가 — 열등기능이 거칠게 튀어나오는 자리 */
  stress: string;
  /** 어떤 일에서 살아나는가 — 직업 이름 나열이 아니라 «일의 성질» */
  work: string;
  /** 가까운 사이에서는 */
  love: string;
}

export type { MbtiType };
