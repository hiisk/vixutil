export interface Tire {
  /** 단면 폭(mm) */
  width: number;
  /** 편평비(%) — 폭 대비 사이드월 높이 */
  aspect: number;
  /** 휠 지름(인치) */
  rim: number;
}

export const TIRES: Tire[] = Object.entries(BY_RIM).flatMap(([rim, list]) =>
  list.split(' ').map(pair => {
    const [width, aspect] = pair.split('/').map(Number);
    return { width, aspect, rim: Number(rim) };
  }),
);

/** 205/55R16 → 205-55r16 */
export const slugOf = (t: Tire): string => `${t.width}-${t.aspect}r${t.rim}`;

/** 사람이 읽고 적는 꼴 */
export const labelOf = (t: Tire): string => `${t.width}/${t.aspect}R${t.rim}`;

export const TIRE_SLUGS = TIRES.map(slugOf);

export const tireOf = (slug: string): Tire | undefined => {
  const m = /^([0-9]{3})-([0-9]{2})r([0-9]{2})$/.exec(slug);
  if (!m) return undefined;
  const [, width, aspect, rim] = m.map(Number);
  return TIRES.find(t => t.width === width && t.aspect === aspect && t.rim === rim);
};

/** 목록과 공유 카드가 같은 그림을 쓴다 */
export const TIRE_ICON = '🛞';

export const RIMS = [...new Set(TIRES.map(t => t.rim))].sort((a, b) => a - b);
