/**
 * 파일 권한 모드 125가지 — 자료를 한 줄도 적지 않는다.
 *
 * 세 자리 8진수의 각 자리는 소유자·그룹·기타의 권한이고, 자리마다 읽기(4)·
 * 쓰기(2)·실행(1)을 더한 값이다. 그러니 모드 하나만 있으면 rwxr-xr-x도,
 * 누가 무엇을 할 수 있는지도, umask도 전부 계산된다(facts.ts).
 *
 * ── 512가지를 다 내지 않는 이유 ─────────────────────────
 * 세 자리 × 여덟 값이면 512가지지만, 그중에는 쓸 일이 없는 것이 많다. 쓰기만
 * 되고 읽기가 안 되는 2, 실행만 되는 1, 쓰기·실행만 되는 3은 실제 시스템에서
 * 거의 보이지 않는다(디렉터리의 1은 뜻이 있지만 그것도 5·7과 함께 쓴다).
 *
 * 그래서 **실제로 쓰이는 다섯 값(0·4·5·6·7)의 모든 조합**만 낸다. 규칙 하나로
 * 125가지가 나오므로 "왜 이건 있고 저건 없나"에 답할 수 있다. 손으로 고르면
 * 그 답이 없어진다.
 */
export const DIGITS = [0, 4, 5, 6, 7] as const;

export const MODES: string[] = DIGITS.flatMap(u =>
  DIGITS.flatMap(g => DIGITS.map(o => `${u}${g}${o}`)),
);

export const modeOf = (slug: string): string | undefined => MODES.find(m => m === slug);

