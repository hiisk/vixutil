/**
 * 저항값 144가지 — 적는 것은 E24 스물넷뿐이다.
 *
 * 색띠도, 오차도, 어느 계열에 드는지도, 10Ω부터 9.1MΩ까지의 여섯 자릿수도
 * 전부 이 스물네 값에서 나온다(facts.ts).
 *
 * ── 왜 공식으로 만들지 않고 적어 두는가 ──────────────────
 * E계열은 한 자릿수를 로그로 고르게 나눈 값이라 10 × 10^(k/24)로 나올 것 같지만,
 * 실제 표는 가운데가 손질돼 있다. 공식은 26·29·32·35·38·42·46을 주는데 표는
 * 27·30·33·36·39·43·47이고, 83 자리만 반대로 82다. 사람이 다루기 좋게 고친
 * 자국이라 계산으로는 되돌릴 수 없다.
 *
 * 그래서 스물넷만 적고, 그 대신 **공식과 어긋나는 자리가 알려진 여덟 곳뿐인지**를
 * 검사가 확인한다. 한 줄을 잘못 베끼면 아홉 곳이 되어 걸린다.
 */
export const E24: number[] = [
  10, 11, 12, 13, 15, 16, 18, 20, 22, 24, 27, 30,
  33, 36, 39, 43, 47, 51, 56, 62, 68, 75, 82, 91,
];

/** E12는 E24에서 한 칸 건너, E6은 E12에서 다시 한 칸 건너다 */
export const E12: number[] = E24.filter((_, i) => i % 2 === 0);
export const E6: number[] = E24.filter((_, i) => i % 4 === 0);

/** 10Ω부터 9.1MΩ까지 — 여섯 자릿수 */
/* 0.1대는 전류 감지에 쓰는 1옴 미만 저항이다 — 실제로 파는 값들이다 */
export const DECADES = [0.1, 1, 10, 100, 1_000, 10_000, 100_000] as const;

/** 옴 단위의 실제 값. 10, 11 … 9,100,000 */
/*
 * 0.1대를 곱하면 12 × 0.1이 1.2000000000000002가 된다 — 그대로 두면 주소와
 * 화면에 그 꼬리가 그대로 나간다. 유효숫자로 다듬어 곱셈 오차를 지운다.
 */
export const VALUES: number[] = DECADES.flatMap(d => E24.map(v => Number((v * d).toPrecision(12))));

export const RESISTOR_SLUGS = VALUES.map(String);

/** 주소는 옴 값 그대로다 — 4k7·4.7k 같은 표기는 나라마다 달라 주소로 삼기 어렵다 */
export const valueOf = (slug: string): number | undefined => VALUES.find(v => String(v) === slug);

/** 목록과 공유 카드가 같은 그림을 쓴다 */
export const RESISTOR_ICON = '⚡';
