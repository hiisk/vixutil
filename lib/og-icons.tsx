/**
 * 이모지에 대응하는 그린 아이콘의 도형들. 100×100 좌표계 그대로 돌려주므로
 * 호출부가 `<g transform>`으로 원하는 크기·위치에 놓는다.
 *
 * 매핑이 없으면 null — 호출부가 이모지를 그대로 쓰게 해서 새 도구가 추가돼도
 * 카드가 비지 않는다.
 */
export function ogGlyph(emoji: string, accent: string): ReactElement[] | null {
  const draw = ICONS[ICON_FOR[emoji]];
  if (!draw) return null;
  return draw(accent).map((node, i) => cloneElement(node, { key: i }));
}

